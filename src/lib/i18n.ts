export const messages: Record<Locale, Record<MessageKey, string>> = {
  vi,
  "zh-TW": zhTW,
};

export function translate(locale: Locale, key: MessageKey, values?: Record<string, string | number>): string {
  let message = messages[locale][key];
  for (const [name, value] of Object.entries(values ?? {})) {
    message = message.replaceAll(`{${name}}`, String(value));
  }
  return message;
}

export function formatNumber(locale: Locale, value: number): string {
  return new Intl.NumberFormat(locale === "vi" ? "vi-VN" : "zh-TW").format(value);
}

export function formatTime(locale: Locale, value: Date): string {
  return new Intl.DateTimeFormat(locale === "vi" ? "vi-VN" : "zh-TW", {
    hour: "2-digit", minute: "2-digit", second: "2-digit",
  }).format(value);
}

