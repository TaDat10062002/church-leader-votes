export const locales = ["vi", "zh-TW"] as const;
export type Locale = (typeof locales)[number];
export const localeCookieName = "app-locale";

export function resolveLocale(value: unknown): Locale {
  return value === "zh-TW" ? "zh-TW" : "vi";
}

export function resolveLocaleCookie(cookieHeader: string | null): Locale {
  const entry = cookieHeader?.split(";").map((part) => part.trim()).find((part) => part.startsWith(`${localeCookieName}=`));
  if (!entry) return "vi";
  try { return resolveLocale(decodeURIComponent(entry.slice(localeCookieName.length + 1))); }
  catch { return "vi"; }
}

